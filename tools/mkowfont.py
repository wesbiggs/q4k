"""The open world's engine's letters: src/ow/ow_font.s.

The engine's text window (src/ow/smooth.s, stlow.s) draws with 96
characters at $A0-$FF of its character set, the lowercase set's first 96
(screen codes $00-$5F: @, a-z, the punctuation and digits, A-Z). They were
the character ROM's; they are now the game's own letters, the bold ones the
screens of text draw in (src/lib/font_data.c, tools/mkfont.py), which
smooth.s's font_copy copies in from here. The table is in OWDATA, which is
the engines' COMMON (OW-DATA), so it costs neither engine a byte of its own.

Three of the 96 are graphics characters nothing types, and are given the
party's lines' pictures instead (GLYPHS below): a coin, a draught and an
arrow.

    tools/mkowfont.py [--font src/lib/font_data.c] [--out src/ow/ow_font.s]
"""

import argparse
import re

COUNT = 96

# Screen code: rows, '#' inked. PETSCII $DD-$DF in the engine's text
# (stlow.s's out(), smooth.s's font_of) are these.
GLYPHS = {
    0x5D: [                     # a coin
        "..####..",
        ".##..##.",
        "##.##.##",
        "##.##.##",
        "##.##.##",
        ".##..##.",
        "..####..",
        "........",
    ],
    0x5E: [                     # a draught
        "..####..",
        "...##...",
        "..####..",
        ".######.",
        ".##.###.",
        ".######.",
        "..####..",
        "........",
    ],
    0x5F: [                     # an arrow
        "........",
        "#....#..",
        ".#...##.",
        "########",
        ".#...##.",
        "#....#..",
        "........",
        "........",
    ],
}


def read_font(path):
    text = open(path).read()
    body = text[text.index("{"):text.index("};")]
    data = [int(h, 16) for h in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    if len(data) < COUNT * 8:
        raise SystemExit(f"{path}: {len(data)} bytes, wanted {COUNT * 8}")
    return data[:COUNT * 8]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--font", default="src/lib/font_data.c")
    ap.add_argument("--out", default="src/ow/ow_font.s")
    args = ap.parse_args()

    data = read_font(args.font)
    for code, rows in GLYPHS.items():
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), code
        for y, row in enumerate(rows):
            data[code * 8 + y] = int(row.replace("#", "1").replace(".", "0"),
                                     2)

    out = [
        f"; GENERATED by tools/mkowfont.py from {args.font} -- do not edit.",
        "; The engine's text window's 96 letters (smooth.s's font_copy), the",
        "; coin at $5D, the draught at $5E and the arrow at $5F.",
        "",
        "        .export ow_font",
        '        .segment "OWDATA"',
        "ow_font:",
    ]
    for i in range(0, len(data), 8):
        out.append("        .byte   " + ", ".join(f"${b:02X}" for b in
                                                 data[i:i + 8])
                   + f"   ; ${i // 8:02X}")
    open(args.out, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
