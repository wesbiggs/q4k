#!/usr/bin/env python3
"""Turn assets/overworld.txt into a C array of screen codes.

The map stores screen codes rather than tile indices, so drawing the viewport
is a straight copy into screen RAM with no per-cell translation -- which is
what makes a full 21x21 redraw affordable at 1MHz.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mktiles

SRC = "assets/overworld.txt"


def main():
    tiles = mktiles.parse("assets/tiles.txt")
    by_char = {t.mapchar: t for t in tiles}

    rows, start = [], None
    for lineno, raw in enumerate(open(SRC), 1):
        line = raw.rstrip("\n")
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("start "):
            _, sx, sy = line.split()
            start = (int(sx), int(sy))
            continue
        unknown = set(line) - set(by_char)
        if unknown:
            sys.exit("%s:%d: no tile uses map character %s -- add one to "
                     "assets/tiles.txt" % (SRC, lineno, sorted(unknown)))
        rows.append(line)

    if start is None:
        sys.exit("%s: missing a 'start <x> <y>' line" % SRC)

    h = len(rows)
    w = len(rows[0])
    if any(len(r) != w for r in rows):
        bad = next(i for i, r in enumerate(rows) if len(r) != w)
        sys.exit("%s: row %d is %d wide, expected %d"
                 % (SRC, bad, len(rows[bad]), w))
    # Wrapping is a bitmask, not a modulo, so the dimensions must be powers
    # of two -- 64x64 masks to & 63 and costs nothing at runtime.
    if w & (w - 1) or h & (h - 1):
        sys.exit("%s: dimensions must be powers of two, got %dx%d" % (SRC, w, h))
    shift = w.bit_length() - 1

    with open("include/q4k/world_data.h", "w") as f:
        f.write("/* GENERATED by tools/mkmap.py from %s -- do not edit. */\n"
                "#ifndef Q4K_WORLD_DATA_H\n#define Q4K_WORLD_DATA_H\n\n"
                "#define WORLD_W      %d\n#define WORLD_H      %d\n"
                "#define WORLD_MASK   0x%02X  /* dimensions are powers of two, "
                "so wrapping is a mask */\n#define WORLD_SHIFT  %d\n\n"
                "extern const unsigned char world_map[WORLD_W * WORLD_H];\n"
                "extern const unsigned char world_start_x;\n"
                "extern const unsigned char world_start_y;\n\n"
                "#endif /* Q4K_WORLD_DATA_H */\n"
                % (SRC, w, h, w - 1, shift))

    with open("src/lib/map_data.c", "w") as f:
        f.write("/* GENERATED by tools/mkmap.py from %s -- do not edit. */\n\n"
                "#include <q4k/world_data.h>\n\n"
                "/* Bulk table: lives above the charset, not in the 12K under it. */\n"
                "#pragma rodata-name (push, \"HIDATA\")\n\n"
                "const unsigned char world_map[WORLD_W * WORLD_H] = {\n" % SRC)
        for y, row in enumerate(rows):
            f.write("    " + " ".join("0x%02X," % by_char[c].code for c in row)
                    + "  /* %2d */\n" % y)
        f.write("};\n\n#pragma rodata-name (pop)\n\n"
                "const unsigned char world_start_x = %d;\n"
                "const unsigned char world_start_y = %d;\n" % start)

    print("mkmap: %dx%d, start %d,%d" % (w, h, start[0], start[1]))


if __name__ == "__main__":
    main()
