#!/usr/bin/env python3
"""Turn assets/overworld.txt into packed C arrays.

The overworld uses only a handful of tiles, so each square is a four-bit
index into `world_tiles`. Rows are run-length coded: a byte is a run, the
high nybble its length less one and the low nybble the index, and
`world_rows` says where each row's runs begin. A row is decoded whole into
a 64-byte buffer when it is wanted (src/lib/world.c); the map as a whole
costs under half what two squares a byte did, which is what made room for
the continents. A second small table gives each index's colour.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mktiles

SRC = "assets/overworld.txt"

# How many squares of open water a port must have out to sea: the length of
# the crossing the player sees on the overworld.
PORT_LANE = 8
COMPASS = {"north": (0, -1), "east": (1, 0), "south": (0, 1), "west": (-1, 0)}


def main():
    tiles = mktiles.parse("assets/tiles.txt")
    by_char = {t.mapchar: t for t in tiles}

    rows, start, ports = [], None, {}
    for lineno, raw in enumerate(open(SRC), 1):
        line = raw.rstrip("\n")
        if line.startswith("#") or not line.strip():
            continue
        if line.startswith("start "):
            _, sx, sy = line.split()
            start = (int(sx), int(sy))
            continue
        if line.startswith("port "):
            _, which, px, py = line.split()
            if which not in COMPASS or which in ports:
                sys.exit("%s:%d: bad or repeated port %r" % (SRC, lineno, which))
            ports[which] = (int(px), int(py))
            continue
        unknown = set(line) - set(by_char)
        if unknown:
            sys.exit("%s:%d: no tile uses map character %s -- add one to "
                     "assets/tiles.txt" % (SRC, lineno, sorted(unknown)))
        rows.append(line)

    if start is None:
        sys.exit("%s: missing a 'start <x> <y>' line" % SRC)

    h = len(rows)
    w = len(rows[0])
    if any(len(r) != w for r in rows):
        bad = next(i for i, r in enumerate(rows) if len(r) != w)
        sys.exit("%s: row %d is %d wide, expected %d"
                 % (SRC, bad, len(rows[bad]), w))
    # Wrapping is a bitmask, not a modulo, so the dimensions must be powers
    # of two -- 64x64 masks to & 63 and costs nothing at runtime.
    if w & (w - 1) or h & (h - 1):
        sys.exit("%s: dimensions must be powers of two, got %dx%d" % (SRC, w, h))
    shift = w.bit_length() - 1

    for which in COMPASS:
        if which not in ports:
            sys.exit("%s: missing a 'port %s <x> <y>' line" % (SRC, which))
    for which, (px, py) in ports.items():
        dx, dy = COMPASS[which]
        if rows[py][px] != "P":
            sys.exit("%s: the %s port at %d,%d is not on a 'P' (it is %r)"
                     % (SRC, which, px, py, rows[py][px]))
        for k in range(1, PORT_LANE + 1):
            sx, sy = (px + dx * k) % w, (py + dy * k) % h
            if rows[sy][sx] != "~":
                sys.exit("%s: the %s port at %d,%d has no open water %d squares "
                         "out to sea (%r at %d,%d)"
                         % (SRC, which, px, py, k, rows[sy][sx], sx, sy))
    if sum(row.count("P") for row in rows) != len(ports):
        sys.exit("%s: every 'P' must be one of the four named ports" % SRC)

    # Screen codes in the order they are indexed; the packing has room for
    # sixteen.
    codes = sorted({by_char[c].code for row in rows for c in row})
    if len(codes) > 16:
        sys.exit("%s: uses %d different tiles; the packed map holds 16"
                 % (SRC, len(codes)))
    index = {code: i for i, code in enumerate(codes)}
    color = {t.code: t.color for t in tiles}

    runs, offsets = [], []
    for row in rows:
        offsets.append(len(runs))
        nyb = [index[by_char[c].code] for c in row]
        x = 0
        while x < w:
            n = 1
            while x + n < w and nyb[x + n] == nyb[x] and n < 16:
                n += 1
            runs.append((n - 1) << 4 | nyb[x])
            x += n

    with open("include/q4k/world_data.h", "w") as f:
        f.write("/* GENERATED by tools/mkmap.py from %s -- do not edit. */\n"
                "#ifndef Q4K_WORLD_DATA_H\n#define Q4K_WORLD_DATA_H\n\n"
                "#define WORLD_W      %d\n#define WORLD_H      %d\n"
                "#define WORLD_MASK   0x%02X  /* dimensions are powers of two, "
                "so wrapping is a mask */\n#define WORLD_SHIFT  %d\n\n"
                "#define WORLD_TILES  %d\n\n"
                "/* Where the ports are, and how far out to sea each has clear water.\n"
                "   Indexed north, east, south, west. */\n"
                "#define PORT_LANE    %d\n"
                "extern const unsigned char world_port_x[4];\n"
                "extern const unsigned char world_port_y[4];\n"
                "\n"
                "/* Each row is runs: the high nybble is a run's length less one,\n"
                "   the low nybble an index into world_tiles. world_rows[y] is\n"
                "   where row y begins. Use world_tile() rather than reading it. */\n"
                "extern const unsigned char world_runs[%d];\n"
                "extern const unsigned char world_rows[WORLD_H];\n"
                "extern const unsigned char world_pages[3];\n"
                "extern const unsigned char world_tiles[WORLD_TILES];\n"
                "extern const unsigned char world_colors[WORLD_TILES];  "
                "/* tile_colors, by index */\n"
                "extern const unsigned char world_start_x;\n"
                "extern const unsigned char world_start_y;\n\n"
                "#endif /* Q4K_WORLD_DATA_H */\n"
                % (SRC, w, h, w - 1, shift, len(codes), PORT_LANE, len(runs)))

    with open("src/lib/map_data.c", "w") as f:
        f.write("/* GENERATED by tools/mkmap.py from %s -- do not edit. */\n\n"
                "#include <q4k/world_data.h>\n\n"
                "/* Bulk table: lives above the charset, not in the 12K under it. */\n"
                "#pragma rodata-name (push, \"HIDATA\")\n\n"
                "const unsigned char world_tiles[WORLD_TILES] = {\n    %s\n};\n\n"
                "const unsigned char world_colors[WORLD_TILES] = {\n    %s\n};\n\n"
                % (SRC, " ".join("0x%02X," % c for c in codes),
                   " ".join("%d," % color[c] for c in codes)))
        f.write("const unsigned char world_port_x[4] = { %s };\n"
                "const unsigned char world_port_y[4] = { %s };\n\n"
                % (", ".join(str(ports[k][0]) for k in COMPASS),
                   ", ".join(str(ports[k][1]) for k in COMPASS)))
        # A row's offset is a byte and a page: the offsets only climb, so the
        # page is how many of three marks the row is past.
        marks = [next((i for i, o in enumerate(offsets) if o >= 256 * k), h)
                 for k in (1, 2, 3)]
        f.write("const unsigned char world_rows[WORLD_H] = {\n")
        for i in range(0, h, 16):
            f.write("    " + " ".join("%d," % (o & 255) for o in offsets[i:i + 16])
                    + "\n")
        f.write("};\n\n/* The first row on each page after the first. */\n"
                "const unsigned char world_pages[3] = { %s };\n"
                % ", ".join(str(m) for m in marks))
        f.write("\nconst unsigned char world_runs[%d] = {\n" % len(runs))
        for i in range(0, len(runs), 16):
            f.write("    " + " ".join("0x%02X," % b for b in runs[i:i + 16]) + "\n")
        f.write("};\n\n#pragma rodata-name (pop)\n\n"
                "const unsigned char world_start_x = %d;\n"
                "const unsigned char world_start_y = %d;\n" % start)

    print("mkmap: %dx%d, %d tiles, %d runs, start %d,%d"
          % (w, h, len(codes), len(runs), start[0], start[1]))


if __name__ == "__main__":
    main()
