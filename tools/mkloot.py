#!/usr/bin/env python3
"""Turn assets/loot.txt into a C table of hidden treasure.

Coordinates rather than a marker in the map, because a town's map characters
are already spoken for. (Nothing is hidden out on the land: it is made fresh
each game.) The cost is that editing a map can leave an entry pointing at a
wall, so every entry is checked against the map it names: it must be a
square you can stand on, and not one that takes you somewhere else.
tools/checkmap.py then checks that it can actually be walked to.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mktiles
import mktowns

SRC = "assets/loot.txt"
KINDS = {"gold": "LOOT_GOLD", "draught": "LOOT_DRAUGHT"}
# The most of each one square may hold. Draughts are counted in a byte.
MOST = {"gold": 65535, "draught": 9}


def parse():
    """[(where, x, y, kind, amount, lineno)] in file order."""
    entries = []
    for lineno, raw in enumerate(open(SRC), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if parts[0] != "loot" or len(parts) != 6:
            sys.exit("%s:%d: expected 'loot <where> <x> <y> <gold|draught> <amount>'"
                     % (SRC, lineno))
        _, where, x, y, kind, amount = parts
        if kind not in KINDS:
            sys.exit("%s:%d: unknown treasure %r" % (SRC, lineno, kind))
        amount = int(amount)
        if not 0 < amount <= MOST[kind]:
            sys.exit("%s:%d: amount %d out of range" % (SRC, lineno, amount))
        entries.append((where, int(x), int(y), kind, amount, lineno))
    return entries


def main():
    tiles = mktiles.parse("assets/tiles.txt")
    by_char = {t.mapchar: t for t in tiles}
    by_code = {t.code: t for t in tiles}
    towns = mktowns.parse(by_char)
    mktowns.resolve(towns, by_char)
    town_index = {t.id: i for i, t in enumerate(towns)}

    entries = parse()
    seen = set()
    out = []
    for where, x, y, kind, amount, lineno in entries:
        here = "%s:%d: %s %d,%d" % (SRC, lineno, where, x, y)
        if (where, x, y) in seen:
            sys.exit("%s: two treasures on one square" % here)
        seen.add((where, x, y))

        if where not in town_index:
            sys.exit("%s: no town called %r in assets/towns.txt"
                     % (here, where))
        t = towns[town_index[where]]
        if not (0 <= x < mktowns.W and 0 <= y < mktowns.H):
            sys.exit("%s: off the map" % here)
        tile = by_code[t.codes[y * mktowns.W + x]]
        if tile.flag in ("TF_BLOCK", "TF_WATER"):
            sys.exit("%s: is %s, which you cannot stand on"
                     % (here, tile.name))
        if (x, y) == t.exit:
            sys.exit("%s: is the way out, which leaves before you could look"
                     % here)
        if any((ex, ey) == (x, y) for ex, ey, _, _ in t.placed):
            sys.exit("%s: somebody is standing there" % here)
        out.append(("TOWN_%s" % where.upper(), x, y, KINDS[kind], amount))

    with open("include/q4k/loot_data.h", "w") as f:
        f.write("/* GENERATED by tools/mkloot.py from %s -- do not edit. */\n"
                "#ifndef Q4K_LOOT_DATA_H\n#define Q4K_LOOT_DATA_H\n\n"
                "#define NUM_LOOT    %d\n\n"
                "#define LOOT_GOLD     0\n#define LOOT_DRAUGHT  1\n\n"
                "typedef struct {\n"
                "    unsigned char map;     /* TOWN_* */\n"
                "    unsigned char x, y;\n"
                "    unsigned char kind;    /* LOOT_* */\n"
                "    unsigned int  amount;\n"
                "} Loot;\n\n"
                "/* Unsized: with no treasures it still holds one, which is never read. */\n"
                "extern const Loot loot_table[];\n\n"
                "#endif /* Q4K_LOOT_DATA_H */\n" % (SRC, len(out)))

    with open("src/lib/loot_data.c", "w") as f:
        f.write("/* GENERATED by tools/mkloot.py from %s -- do not edit. */\n\n"
                "#include <q4k/loot_data.h>\n"
                "#include <q4k/town_data.h>\n\n"
                "#pragma rodata-name (push, \"HIDATA\")\n\n"
                "const Loot loot_table[] = {\n" % SRC)
        for where, x, y, kind, amount in out:
            f.write("    { %-15s %2d, %2d, %s, %5d },\n"
                    % (where + ",", x, y, kind, amount))
        if not out:
            f.write("    { 0 },\n")      # C has no empty arrays
        f.write("};\n\n#pragma rodata-name (pop)\n")

    print("mkloot: %d treasures" % len(out))


if __name__ == "__main__":
    main()
