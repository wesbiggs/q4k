#!/usr/bin/env python3
"""The game's music: SID files, checked, and which scene plays what.

    tools/mksid.py wrap BIN LBL OUT.sid   a linked tune (cfg/sid.cfg) as a PSID
    tools/mksid.py map                    assets/music.txt -> the scene table
    tools/mksid.py disk OUTDIR DIR...     every tune assets/music.txt names,
                                          checked, as the game's disk files

The game plays standard SID files (PSID): a 6502 player and its song data,
with an init routine (the song number in A) and a play routine called 60 or
50 times a second. It keeps one tune at a time under the KERNAL, at
$E800-$FFF9, and loads each from the disk when a scene wants it
(src/lib/tune.c, src/lib/music.s). assets/music.txt is the map from scene to
(SID file, song); `map` makes it into include/q4k/music_map.h and
src/lib/music_map.c, which are committed like the other generated sources.

`disk` looks for each SID named there in the DIRs, in order (build/sid for
the ones the build makes, like the theme, then assets/music), runs it through
an emulated 6502 (tools/sid6502.py) to see that the game can host it, and
writes it as m.NAME: loaded at $E7C0, a 64-byte header there, then the image
at its own address:

    $E7C0  init, play (little-endian)
    $E7C4  how many songs
    $E7C5  the volume register to put back after a pause ($D418)
    $E7C6  a byte a song: 1 to call play at 60 Hz (PSID "CIA"), 0 at the
           frame rate (PSID "VBI": 50 Hz on PAL, which the game gets by
           skipping one call in six of its 60 Hz interrupt)

What a tune may do, which the check enforces:
  - be a PSID (not an RSID, which wants the machine to itself), with a play
    routine (not one that installs its own interrupt), for one SID chip;
  - load within $E800-$FFF9, and run only from there;
  - write only there, the SID's voices 1 and 2, its filter and volume
    ($D415-$D418), and zero page $FB-$FE: voice 3 is the sound effects';
  - read only those, the stack, and $02A6 (the KERNAL's PAL flag);
  - take at most PLAY_BUDGET cycles a call.
A tune that breaks one is refused with the reason, before it reaches the disk.
"""

import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from sid6502 import CPU, Stop  # noqa: E402

MAP_SRC = "assets/music.txt"
MAP_H = "include/q4k/music_map.h"
MAP_C = "src/lib/music_map.c"

AREA_LO, AREA_HI = 0xE800, 0xFFFA       # the tune's (cfg/sid.cfg, music.s)
HEADER_AT = 0xE7C0                      # 64 bytes between vault slot 0 and it
HEADER_SIZE = 0x40
MAX_SONGS = HEADER_SIZE - 6
ZP_FREE = range(0xFB, 0xFF)
SID_OK = set(range(0xD400, 0xD40E)) | set(range(0xD415, 0xD419))
VOICE3 = range(0xD40E, 0xD415)
PALFLAG = 0x02A6
PLAY_BUDGET = 4000                      # cycles a call: a quarter of a frame
FRAMES = 2000                           # play calls the check runs, per song and clock


def die(msg):
    sys.exit("mksid: " + msg)


# --- the map ---------------------------------------------------------------

def read_map():
    """[(scene, sid name, song from 1)] in the file's order."""
    rows, seen = [], set()
    for n, raw in enumerate(open(MAP_SRC), 1):
        line = raw.split("#")[0].split()
        if not line:
            continue
        if len(line) != 3 or not line[2].isdigit():
            die("%s:%d: want: scene sid song" % (MAP_SRC, n))
        scene, sid, song = line[0].lower(), line[1].lower(), int(line[2])
        if not re.fullmatch(r"[a-z][a-z0-9_]*", scene) or scene in seen:
            die("%s:%d: scene %r is not a fresh name" % (MAP_SRC, n, scene))
        if not re.fullmatch(r"[a-z0-9]{1,14}", sid):
            die("%s:%d: a SID's name is 1 to 14 letters and digits: %r" % (MAP_SRC, n, sid))
        if not 1 <= song <= MAX_SONGS:
            die("%s:%d: song %d (they count from 1)" % (MAP_SRC, n, song))
        seen.add(scene)
        rows.append((scene, sid, song))
    if not rows:
        die("%s: no scenes" % MAP_SRC)
    return rows


def sid_names(rows):
    names = []
    for _, sid, _ in rows:
        if sid not in names:
            names.append(sid)
    return names


def cmd_map():
    rows = read_map()
    names = sid_names(rows)
    if len(names) > 254:
        die("more than 254 SID files")
    h = ["/* GENERATED by tools/mksid.py from %s -- do not edit. */" % MAP_SRC,
         "",
         "#ifndef Q4K_MUSIC_MAP_H",
         "#define Q4K_MUSIC_MAP_H",
         "",
         "/* The scenes music_scene() is told about; each plays a song of a SID",
         "   file, which tune_file[] and tune_song[] say (src/lib/music_map.c). */"]
    for i, (scene, sid, song) in enumerate(rows):
        h.append("#define MUSIC_%-10s %2d   /* %s, song %d */" % (scene.upper(), i, sid, song))
    h += ["#define MUSIC_COUNT      %2d" % len(rows),
          "#define MUSIC_FILES      %2d" % len(names),
          "",
          "extern const char *const   tune_name[MUSIC_FILES];   /* on the disk */",
          "extern const unsigned char tune_file[MUSIC_COUNT];   /* into tune_name */",
          "extern const unsigned char tune_song[MUSIC_COUNT];   /* from 0, for init */",
          "",
          "#endif", ""]
    c = ["/* GENERATED by tools/mksid.py from %s -- do not edit. */" % MAP_SRC,
         "",
         "#include <q4k/music_map.h>",
         "",
         "const char *const tune_name[MUSIC_FILES] = {",
         "    " + ", ".join('"m.%s"' % n for n in names),
         "};",
         "const unsigned char tune_file[MUSIC_COUNT] = {",
         "    " + ", ".join(str(names.index(sid)) for _, sid, _ in rows),
         "};",
         "const unsigned char tune_song[MUSIC_COUNT] = {",
         "    " + ", ".join(str(song - 1) for _, _, song in rows),
         "};",
         ""]
    open(MAP_H, "w").write("\n".join(h))
    open(MAP_C, "w").write("\n".join(c))
    print("mksid: %d scenes, %d SID file%s: %s" % (
        len(rows), len(names), "" if len(names) == 1 else "s", ", ".join(names)))


# --- PSID files -------------------------------------------------------------

class Sid:
    pass


def parse_sid(path):
    data = open(path, "rb").read()
    s = Sid()
    s.path = path
    magic = data[:4]
    if magic == b"RSID":
        die("%s is an RSID: it wants the whole machine, and a game cannot give it that" % path)
    if magic != b"PSID":
        die("%s is not a SID file" % path)
    (s.version, off, load, s.init, s.play, s.songs, s.start,
     s.speed) = struct.unpack(">HHHHHHHI", data[4:22])
    s.title = data[22:54].split(b"\0")[0].decode("latin-1")
    s.author = data[54:86].split(b"\0")[0].decode("latin-1")
    flags = 0
    if s.version >= 2 and off >= 0x7C:
        flags = struct.unpack(">H", data[118:120])[0]
        if s.version >= 3 and (data[122] or (s.version >= 4 and data[123])):
            die("%s wants more than one SID chip" % path)
    if flags & 1:
        die("%s is in Compute!'s MUS format, not 6502 code" % path)
    body = data[off:]
    if load == 0:
        load, body = body[0] | body[1] << 8, body[2:]
    s.load, s.image = load, body
    s.end = load + len(body)
    if s.init == 0:
        s.init = load
    if s.play == 0:
        die("%s has no play routine (it sets up an interrupt of its own)" % path)
    if not 1 <= s.songs <= MAX_SONGS:
        die("%s has %d songs; the game takes 1 to %d" % (path, s.songs, MAX_SONGS))
    if s.load < AREA_LO or s.end > AREA_HI:
        die("%s loads at $%04X-$%04X; the game's tunes go at $%04X-$%04X: "
            "relocate it there" % (path, s.load, s.end - 1, AREA_LO, AREA_HI - 1))
    return s


def cia(s, song):
    """Is song (from 0) called at 60 Hz rather than at the frame rate?"""
    return bool(s.speed >> min(song, 31) & 1)


def check(s):
    """Run every song on both clocks; returns (volume, worst play, voices)."""
    worst, vol, voices = 0, None, set()
    for song in range(s.songs):
        for pal in (1, 0):
            mem = bytearray(65536)
            mem[s.load:s.end] = s.image
            mem[PALFLAG] = pal
            where = ["init"]

            def fail(msg):
                raise Stop("%s, song %d (%s, %s): %s" % (
                    s.path, song + 1, "PAL" if pal else "NTSC", where[0], msg))

            def on_write(a, v):
                nonlocal vol
                if AREA_LO <= a < AREA_HI or a in ZP_FREE:
                    return
                if a in SID_OK:
                    if a < 0xD407:
                        voices.add(1)
                    elif a < 0xD40E:
                        voices.add(2)
                    if a == 0xD418 and pal:
                        vol = v
                    return
                if a in VOICE3:
                    fail("writes $%04X: voice 3 is the sound effects'" % a)
                fail("writes $%04X, outside what a tune may touch" % a)

            def on_read(a):
                if 0xD400 <= a <= 0xD41C:
                    return 0
                if (AREA_LO <= a < AREA_HI or a in ZP_FREE or a == PALFLAG
                        or 0x100 <= a < 0x200):
                    return None
                fail("reads $%04X, outside what a tune may touch" % a)

            def on_fetch(pc):
                if not AREA_LO <= pc < AREA_HI:
                    fail("runs code at $%04X, outside the tune (the KERNAL is "
                         "banked out while it plays)" % pc)

            cpu = CPU(mem, on_read, on_write, on_fetch)
            try:
                cpu.call(s.init, a=song, limit=500000)
                where[0] = "play"
                for frame in range(FRAMES):
                    where[0] = "play, call %d" % (frame + 1)
                    n = cpu.call(s.play, limit=50000)
                    worst = max(worst, n)
            except Stop as e:
                msg = str(e)
                die(msg if msg.startswith(s.path) else
                    "%s, song %d (%s, %s): %s" % (s.path, song + 1,
                                                  "PAL" if pal else "NTSC", where[0], msg))
            if cpu.low_sp < 0xFF - 64:
                die("%s, song %d: uses %d bytes of stack" % (s.path, song + 1, 0xFF - cpu.low_sp))
    if worst > PLAY_BUDGET:
        die("%s: play takes up to %d cycles; the game allows %d" % (s.path, worst, PLAY_BUDGET))
    return (0x0F if vol is None else vol), worst, voices


def find(name, dirs):
    for d in dirs:
        p = os.path.join(d, name + ".sid")
        if os.path.exists(p):
            return p
    die("no %s.sid in %s" % (name, " or ".join(dirs)))


def cmd_disk(outdir, dirs):
    rows = read_map()
    names = sid_names(rows)
    os.makedirs(outdir, exist_ok=True)
    for f in os.listdir(outdir):
        if f.startswith("m."):
            os.remove(os.path.join(outdir, f))
    for name in names:
        s = parse_sid(find(name, dirs))
        for scene, sid, song in rows:
            if sid == name and song > s.songs:
                die("%s: scene %s wants song %d of %s, which has %d" % (
                    MAP_SRC, scene, song, s.path, s.songs))
        vol, worst, voices = check(s)
        head = struct.pack("<HHBB", s.init, s.play, s.songs, vol)
        head += bytes(int(cia(s, i)) for i in range(s.songs))
        head = head.ljust(s.load - HEADER_AT, b"\0")
        with open(os.path.join(outdir, "m." + name), "wb") as f:
            f.write(struct.pack("<H", HEADER_AT) + head + s.image)
        print("mksid: m.%s: %s, $%04X-$%04X, %d song%s, voices %s, play %d cycles at most" % (
            name, os.path.basename(s.path), s.load, s.end - 1, s.songs,
            "" if s.songs == 1 else "s", "+".join(map(str, sorted(voices))) or "none", worst))
    open(os.path.join(outdir, ".stamp"), "w").close()


# --- wrapping a linked tune --------------------------------------------------

def cmd_wrap(binpath, lblpath, out, title, author, released):
    labels = {}
    for line in open(lblpath):
        parts = line.split()
        if len(parts) == 3 and parts[0] == "al":
            labels[parts[2].lstrip(".")] = int(parts[1], 16)
    image = open(binpath, "rb").read()
    load = labels["__SID_START__"]
    header = b"PSID" + struct.pack(">HHHHHHHI", 2, 0x7C, 0, labels["init"],
                                   labels["play"], 1, 1, 1)
    for text in (title, author, released):
        header += text.encode("latin-1")[:32].ljust(32, b"\0")
    # Flags: PAL and NTSC both (the player picks its pitches by $02A6), either
    # chip (no filter); no relocation range, one SID.
    header += struct.pack(">HBBBB", (3 << 2) | (3 << 4), 0, 0, 0, 0)
    assert len(header) == 0x7C
    with open(out, "wb") as f:
        f.write(header + struct.pack("<H", load) + image)
    print("mksid: %s, %d bytes at $%04X" % (out, len(image), load))


def main(argv):
    if argv[:1] == ["map"]:
        cmd_map()
    elif argv[:1] == ["disk"] and len(argv) >= 3:
        cmd_disk(argv[1], argv[2:])
    elif argv[:1] == ["wrap"] and len(argv) == 4:
        cmd_wrap(argv[1], argv[2], argv[3], "Quest for the King",
                 "Wes Biggs", "2026 Quest for the King")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
