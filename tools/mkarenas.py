#!/usr/bin/env python3
"""Turn assets/arenas.txt into C tables.

One battle field per kind of overworld ground. Like the towns, each map is a
screenful of screen codes, so drawing it is a copy.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import checkmap
import mktiles
import rle

SRC = "assets/arenas.txt"
W, H = 21, 19
MARKERS = "@m"


class Arena:
    __slots__ = ("tile", "size", "rows", "hero", "monster", "codes")


def parse(by_name):
    arenas, cur, reading = [], None, False
    for lineno, raw in enumerate(open(SRC), 1):
        line = raw.rstrip("\n")
        if reading:
            if not line.strip():
                reading = False
                continue
            if len(line) != W:
                sys.exit("%s:%d: row is %d wide, expected %d"
                         % (SRC, lineno, len(line), W))
            cur.rows.append(line)
            continue
        if not line.strip() or line.startswith("#"):
            continue

        word = line.split(None, 1)[0]
        if word == "arena":
            parts = line.split()
            if len(parts) not in (2, 3) or parts[1] not in by_name:
                sys.exit("%s:%d: expected 'arena <tile> [size]'"
                         % (SRC, lineno))
            cur = Arena()
            cur.tile, cur.rows = by_name[parts[1]], []
            cur.size = int(parts[2]) if len(parts) == 3 else 1
            arenas.append(cur)
        elif word == "map":
            reading = True
        else:
            sys.exit("%s:%d: unexpected %r" % (SRC, lineno, word))

    for a in arenas:
        if len(a.rows) != H:
            sys.exit("arena %s has %d rows, need %d"
                     % (a.tile.name, len(a.rows), H))
    return arenas


def resolve(a, by_char, walkable):
    """Find the two starting squares and put ground under them."""
    grid = [list(r) for r in a.rows]
    found = {}
    for y in range(H):
        for x in range(W):
            c = grid[y][x]
            if c in MARKERS:
                if c in found:
                    sys.exit("arena %s has two %r" % (a.tile.name, c))
                found[c] = (x, y)
            elif c not in by_char or by_char[c].flag == mktiles.ACTOR:
                sys.exit("arena %s: map character %r is not a terrain tile"
                         % (a.tile.name, c))

    for c in MARKERS:
        if c not in found:
            sys.exit("arena %s has no %r start" % (a.tile.name, c))
        x, y = found[c]
        under = None
        for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and grid[ny][nx] in walkable:
                under = grid[ny][nx]
                break
        grid[y][x] = under or a.tile.mapchar
    a.hero, a.monster = found["@"], found["m"]

    # The monster only ever walks towards you, so a field where it cannot
    # get to you is a fight nobody can finish. A big one needs its whole
    # body clear, so its moves are flooded as its top-left corner.
    n = a.size

    def fits(x, y):
        return (x + n <= W and y + n <= H
                and all(grid[y + j][x + i] in walkable
                        for j in range(n) for i in range(n)))

    if not fits(*a.monster):
        sys.exit("arena %s: the monster does not fit where it starts"
                 % a.tile.name)
    hx, hy = a.hero
    seen = checkmap.flood(fits, a.monster, W, H, False)
    near = any(fits(x, y) and not (x <= hx < x + n and y <= hy < y + n)
               and any(x <= hx + dx < x + n and y <= hy + dy < y + n
                       for dx, dy in ((0, 1), (0, -1), (1, 0), (-1, 0)))
               for x, y in seen)
    if not near:
        sys.exit("arena %s: the monster cannot reach the hero" % a.tile.name)

    a.codes = [by_char[c].code for row in grid for c in row]


def main():
    tiles = mktiles.parse("assets/tiles.txt")
    by_char = {t.mapchar: t for t in tiles}
    by_name = {t.name: t for t in tiles}
    walkable = {c for c, t in by_char.items()
                if t.flag not in ("TF_BLOCK", "TF_WATER", mktiles.ACTOR)}

    arenas = parse(by_name)
    for a in arenas:
        resolve(a, by_char, walkable)

    with open("include/q4k/arena_data.h", "w") as f:
        f.write("/* GENERATED by tools/mkarenas.py from %s -- do not edit. */\n"
                "#ifndef Q4K_ARENA_DATA_H\n#define Q4K_ARENA_DATA_H\n\n"
                "#include <q4k/town_data.h>   /* LOCAL_W, LOCAL_H */\n\n"
                "#define NUM_ARENAS  %d\n\n"
                "/* The overworld tile each field is for. */\n"
                "extern const unsigned char arena_tile[NUM_ARENAS];\n"
                "/* Run-length encoded: unpack with rle_unpack(). */\n"
                "extern const unsigned char *const arena_map[NUM_ARENAS];\n"
                "extern const unsigned char arena_hx[NUM_ARENAS];\n"
                "extern const unsigned char arena_hy[NUM_ARENAS];\n"
                "extern const unsigned char arena_mx[NUM_ARENAS];\n"
                "extern const unsigned char arena_my[NUM_ARENAS];\n\n"
                "#endif /* Q4K_ARENA_DATA_H */\n" % (SRC, len(arenas)))

    packed = 0
    with open("src/lib/arena_data.c", "w") as f:
        f.write("/* GENERATED by tools/mkarenas.py from %s -- do not edit. */\n\n"
                "#include <q4k/arena_data.h>\n\n"
                "#pragma rodata-name (push, \"HIDATA\")\n\n" % SRC)

        def table(name, values, fmt="%d"):
            f.write("const unsigned char %s[NUM_ARENAS] = { %s };\n"
                    % (name, ", ".join(fmt % v for v in values)))

        table("arena_tile", [a.tile.code for a in arenas], "0x%02X")
        table("arena_hx", [a.hero[0] for a in arenas])
        table("arena_hy", [a.hero[1] for a in arenas])
        table("arena_mx", [a.monster[0] for a in arenas])
        table("arena_my", [a.monster[1] for a in arenas])

        f.write("\n")
        packed = 0
        for i, a in enumerate(arenas):
            f.write("/* %s */\n" % a.tile.name)
            packed += rle.write_c(f, "map_%d" % i, a.codes, W)
            f.write("\n")
        f.write("const unsigned char *const arena_map[NUM_ARENAS] = {\n    %s\n};\n\n"
                "#pragma rodata-name (pop)\n"
                % ", ".join("map_%d" % i for i in range(len(arenas))))

    print("mkarenas: %d arenas (%s), packed to %d bytes"
          % (len(arenas), ", ".join(a.tile.name for a in arenas), packed))


if __name__ == "__main__":
    main()
