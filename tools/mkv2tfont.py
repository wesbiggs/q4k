#!/usr/bin/env python3
"""The C64's own lowercase letters as a font for vic2orious's v2t.inc.

    tools/mkv2tfont.py CHARGEN.bin > src/ow/vic2/font.inc

v2t.inc draws proportional text from a font.inc of glyphs cut into byte
columns (assets/vic2/lib/v2t.inc, and the format in
assets/splash-kit/docs/v2t-format.md). vic2orious makes one from the
character ROM, as this does: the ROM's lowercase set (the second 2K), each
glyph trimmed to the columns with ink and given one column of spacing, a
blank glyph four wide, and ASCII mapped to the set as the game's text.c
maps it (a-z, A-Z, digits and punctuation; what the set has no glyph for is
a blank). The result is checked in, so that the build needs no ROM: run
this again only to change the font. 8 pixels high, so a line is a
character row and nothing shares a row's colours. It goes in RODATA
whatever segment includes it: owtalk's PICCODE has no room for it.
"""

import sys

H = 8


def screen_code(a):
    if 32 <= a <= 63:
        return a
    if a == 64:
        return 0
    if 65 <= a <= 90:
        return a - 65 + 0x41
    if 97 <= a <= 122:
        return a - 97 + 1
    return {91: 0x1B, 93: 0x1D}.get(a)


def main():
    rom = open(sys.argv[1], "rb").read()
    if len(rom) != 4096:
        sys.exit("mkv2tfont: %s is not a 4K character ROM" % sys.argv[1])
    ws, nbs, offs, data = [], [], [], []
    hang = 8
    for a in range(32, 128):
        sc = screen_code(a)
        rows = list(rom[0x800 + sc * 8:0x800 + sc * 8 + 8]) if sc is not None else [0] * 8
        ink = 0
        for r in rows:
            ink |= r
        if not ink:
            ws.append(4)
            nbs.append(0)
            offs.append(0)
            continue
        left = max(b for b in range(8) if ink & (1 << b))   # bit 7 is the leftmost
        right = min(b for b in range(8) if ink & (1 << b))
        cols = left - right + 1
        shift = 7 - left
        ws.append(cols + 1)
        hang = min(hang, 1)
        nbs.append(1)
        offs.append(len(data))
        data.extend((r << shift) & 0xFF for r in rows)
    out = ["; generated by tools/mkv2tfont.py from the character ROM's lowercase set:",
           "; do not edit. 8 pixels high, in byte columns (v2t.inc's font.inc).",
           "V2T_FONT_H = %d" % H, "V2T_FONT_HANG = %d" % hang,
           "        .pushseg",
           "        .segment \"RODATA\"            ; (below $4000 in owtalk: only read)"]

    def table(label, vals):
        out.append(label + ":")
        for i in range(0, len(vals), 8):
            out.append("        .byte " + ",".join(vals[i:i + 8]))

    table("v2t_font_w", [str(w) for w in ws])
    table("v2t_font_nb", [str(n) for n in nbs])
    table("v2t_font_lo", ["<(v2t_font_data+%d)" % o for o in offs])
    table("v2t_font_hi", [">(v2t_font_data+%d)" % o for o in offs])
    table("v2t_font_data", ["$%02x" % b for b in data])
    out.append("        .popseg")
    print("\n".join(out))


main()
