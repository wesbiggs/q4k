#!/usr/bin/env python3
"""The open world's REU load cache (src/lib/ow_cache.s): what the build knows.

Every file the open world loads through the cache (the engines, their
overlays and .hi files, OW-DATA, owtown, owparty, the tile sets, the fight
module and its fields and sprites, the tunes) has a place in the REU decided
here: a directory entry in bank 1, at 8 times a hash of its name, and room
for the file itself after the directory, in the order given. The bootstrap
(ow_cinit.s) lays that directory out when the REU's does not carry this
build's stamp; the loader fills a file's room the first time it loads it,
and fetches it from there every time after.

    mkowcache.py salt NAME...           which salts give NAMEs no collision
    mkowcache.py dir OUT.s FILE=NAME... [--glob PATTERN]...
        the bootstrap's table (owc_tab) and the stamp (owc_sig); fails if
        two names share an entry
    mkowcache.py image OUT.reu KB FILE=NAME... [--glob PATTERN]...
        an REU image as the loader would leave it with every file in it,
        for VICE's -reuimage (tools/screendump.py --reucache)

A --glob's files are named by their basenames, as the disk has them. The
hash and its salt are the loader's: the salt is include/q4k/owcache.inc's.
"""

import glob
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = os.path.join(ROOT, "include", "q4k", "owcache.inc")

BANK = 1                # the directory's bank (bank 0 is the engine's)
DIR = 0x0000            # 256 entries of 8 bytes
HDR = 0x0800            # the magic and the stamp
DATA = 0x0900           # the files, from here up
MAGIC = bytes([0x51, 0x43])


def salt():
    m = re.search(r"OWC_SALT\s*=\s*(\d+)", open(INC).read())
    return int(m.group(1))


def pet(name):
    """The name as cc65 compiles it, and as the disk has it: PETSCII, the
    lower case letters at $41-$5A."""
    return bytes(ord(c) - 32 if "a" <= c <= "z" else ord(c) for c in name)


def hashes(name, s):
    """ow_cache.s's owc_look: the entry, and the check its last byte holds
    (bit 0 is whether the file is there yet)."""
    h = ck = 0
    for c in pet(name):
        ck = (ck + c) & 255
        h = ((h << 1) | (h >> 7)) & 255
        h = ((h ^ c) + s) & 255
    return h, (ck & 0x7E) | 0x80


def files(args):
    out, pats = [], []
    i = 0
    while i < len(args):
        if args[i] == "--glob":
            pats.append(args[i + 1])
            i += 2
            continue
        path, name = args[i].split("=")
        out.append((path, name))
        i += 1
    for p in pats:
        for path in sorted(glob.glob(p)):
            if not path.endswith(".stamp"):
                out.append((path, os.path.basename(path)))
    return out


def entries(args):
    s = salt()
    ents, seen = [], {}
    for path, name in files(args):
        data = open(path, "rb").read()
        if len(data) < 3:
            sys.exit("mkowcache: %s: empty" % path)
        h, ck = hashes(name, s)
        if h in seen:
            sys.exit("mkowcache: %s and %s share entry %d (salt %d): pick "
                     "another salt with 'mkowcache.py salt' and put it in %s"
                     % (seen[h], name, h, s, os.path.relpath(INC, ROOT)))
        seen[h] = name
        start = data[0] | data[1] << 8
        ents.append((name, h, ck, start, data[2:]))
    stamp = hashlib.sha1()
    for name, h, ck, start, body in ents:
        stamp.update(name.encode() + bytes([start & 255, start >> 8]) + body)
    return ents, stamp.digest()[:4]


def write_dir(out, args):
    ents, stamp = entries(args)
    w = []
    w.append("; GENERATED by tools/mkowcache.py -- do not edit.")
    w.append(";")
    w.append("; The REU cache's files, for the bootstrap to lay the directory out")
    w.append("; (ow_cinit.s): each one's entry, its check, where it loads and how")
    w.append("; long it is; and the magic and this build's stamp.")
    w.append("")
    w.append("        .export owc_sig, owc_n, owc_tab")
    w.append('        .segment "RODATA"')
    w.append("owc_sig: .byte " + ",".join("$%02X" % b for b in MAGIC + stamp))
    w.append("owc_n:   .byte %d" % len(ents))
    w.append("owc_tab:")
    total = 0
    for name, h, ck, start, body in ents:
        n = len(body)
        total += n
        w.append("        .byte $%02X,$%02X,$%02X,$%02X,$%02X,$%02X  ; %s"
                 % (h, ck, start & 255, start >> 8, n & 255, n >> 8, name))
    w.append("")
    open(out, "w").write("\n".join(w))
    print("mkowcache: %d files, %d bytes, stamp %s -> %s"
          % (len(ents), total, stamp.hex(), os.path.relpath(out, ROOT)))


def write_image(out, kb, args):
    ents, stamp = entries(args)
    size = kb * 1024
    banks = size >> 16
    img = bytearray(size)
    base = BANK << 16
    nxt = base + DATA
    for name, h, ck, start, body in ents:
        n = len(body)
        if nxt + n > banks << 16:
            continue                    # (ow_cinit.s leaves it out too)
        img[nxt:nxt + n] = body
        e = base + DIR + h * 8
        img[e:e + 8] = bytes([nxt & 255, (nxt >> 8) & 255, nxt >> 16,
                              n & 255, n >> 8, start & 255, start >> 8,
                              ck | 1])
        nxt += n
    img[base + HDR:base + HDR + 6] = MAGIC + stamp
    open(out, "wb").write(img)
    print("mkowcache: %s, %dK, %d bytes of files"
          % (os.path.relpath(out, ROOT), kb, nxt - base - DATA))


def find_salt(names):
    good = []
    for s in range(256):
        if len({hashes(n, s)[0] for n in names}) == len(names):
            good.append(s)
    print("salts with no collision:", " ".join(map(str, good)) or "none")


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    if cmd == "salt":
        find_salt(sys.argv[2:])
    elif cmd == "dir":
        write_dir(sys.argv[2], sys.argv[3:])
    elif cmd == "image":
        write_image(sys.argv[2], int(sys.argv[3]), sys.argv[4:])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
