#!/usr/bin/env python3
"""Turn assets/tiles.txt into C: glyph bitmaps, codes, flags and colours.

Generated output is checked in so the build needs no Python, but the Makefile
regenerates it whenever the asset changes.
"""

import sys

COLORS = {
    "black": 0, "white": 1, "red": 2, "cyan": 3, "violet": 4, "green": 5,
    "blue": 6, "yellow": 7, "orange": 8, "brown": 9, "lightred": 10,
    "gray1": 11, "gray2": 12, "lightgreen": 13, "lightblue": 14, "gray3": 15,
}
FLAGS = {"pass": "TF_PASS", "block": "TF_BLOCK",
         "water": "TF_WATER", "enter": "TF_ENTER"}
# Actors are drawn over terrain and carry no terrain properties, so they sit
# outside the contiguous block the flag and colour tables index into.
ACTOR = "actor"


class Tile:
    __slots__ = ("name", "mapchar", "code", "flag", "color", "rows")


def parse(path):
    tiles, cur = [], None
    for lineno, raw in enumerate(open(path), 1):
        line = raw.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#") and not (
                cur and len(cur.rows) < 8):
            # A '#' inside a bitmap block is pixel data, not a comment.
            if cur is None or len(cur.rows) >= 8:
                continue
        if line.startswith("tile "):
            parts = line.split()
            if len(parts) != 6:
                sys.exit("%s:%d: expected 'tile name char code flag colour'"
                         % (path, lineno))
            cur = Tile()
            cur.name, cur.mapchar = parts[1], parts[2]
            cur.code = int(parts[3], 0)
            if parts[4] != ACTOR and parts[4] not in FLAGS:
                sys.exit("%s:%d: unknown flag %r" % (path, lineno, parts[4]))
            if parts[5] not in COLORS:
                sys.exit("%s:%d: unknown colour %r" % (path, lineno, parts[5]))
            cur.flag = FLAGS.get(parts[4], ACTOR)
            cur.color = COLORS[parts[5]]
            cur.rows = []
            tiles.append(cur)
        elif cur is not None and len(cur.rows) < 8:
            if len(line) != 8 or set(line) - set(".#"):
                sys.exit("%s:%d: bitmap rows must be 8 chars of '.' or '#', "
                         "got %r" % (path, lineno, line))
            cur.rows.append(int(line.replace(".", "0").replace("#", "1"), 2))

    for t in tiles:
        if len(t.rows) != 8:
            sys.exit("tile %s has %d bitmap rows, need 8" % (t.name, len(t.rows)))
    return tiles


def check_contiguous(tiles):
    """Tile properties are indexed by `code - base`, so gaps would silently
    hand back another tile's flags."""
    terrain = [t for t in tiles if t.flag != ACTOR]
    base = terrain[0].code
    for i, t in enumerate(terrain):
        if t.code != base + i:
            sys.exit("tile %s has code $%02X; codes must run contiguously from "
                     "$%02X (found a gap at index %d)" % (t.name, t.code, base, i))
    return base, terrain


def main():
    src = "assets/tiles.txt"
    tiles = parse(src)
    base, terrain = check_contiguous(tiles)

    with open("include/q4k/tiles.h", "w") as h:
        h.write("/* GENERATED by tools/mktiles.py from %s -- do not edit. */\n"
                "#ifndef Q4K_TILES_H\n#define Q4K_TILES_H\n\n"
                "/* Terrain properties are indexed by screen code - TILE_BASE. */\n"
                "#define TILE_BASE   0x%02X\n"
                "#define TILE_COUNT  %d   /* terrain only, contiguous */\n"
                "#define TILE_TOTAL  %d   /* terrain + actors          */\n\n"
                "#define TF_PASS     0  /* walk onto it freely        */\n"
                "#define TF_BLOCK    1  /* impassable                 */\n"
                "#define TF_WATER    2  /* impassable on foot         */\n"
                "#define TF_ENTER    3  /* steps into a location      */\n\n"
                % (src, base, len(terrain), len(tiles)))
        for t in tiles:
            h.write("#define T_%-9s 0x%02X\n" % (t.name.upper(), t.code))
        h.write("\nextern const unsigned char tile_flags[TILE_COUNT];\n"
                "extern const unsigned char tile_colors[TILE_COUNT];\n\n"
                "/* Names, indexed as the tile list is declared. Kept in a\n"
                "   separate module so only tools that print them pay for it. */\n"
                "extern const char *const tile_names[TILE_TOTAL];\n"
                "extern const unsigned char tile_codes[TILE_TOTAL];\n\n"
                "/* Copy the ROM font to RAM and patch every tile glyph in. */\n"
                "void tiles_install(void);\n\n#endif /* Q4K_TILES_H */\n")

    with open("src/lib/tiles_data.c", "w") as c:
        c.write("/* GENERATED by tools/mktiles.py from %s -- do not edit. */\n\n"
                "#include <q4k/charset.h>\n#include <q4k/tiles.h>\n\n" % src)
        c.write("const unsigned char tile_flags[TILE_COUNT] = {\n")
        for t in terrain:
            c.write("    %-8s /* $%02X %s */\n" % (t.flag + ",", t.code, t.name))
        c.write("};\n\nconst unsigned char tile_colors[TILE_COUNT] = {\n")
        for t in terrain:
            c.write("    %2d,      /* $%02X %s */\n" % (t.color, t.code, t.name))
        c.write("};\n\n")

        c.write("static const unsigned char glyphs[%d][8] = {\n" % len(tiles))
        for t in tiles:
            c.write("    { %s },  /* %s */\n"
                    % (", ".join("0x%02X" % b for b in t.rows), t.name))
        c.write("};\n\nstatic const unsigned char codes[%d] = {\n    %s\n};\n\n"
                % (len(tiles), ", ".join("0x%02X" % t.code for t in tiles)))
        c.write("void tiles_install(void)\n{\n"
                "    unsigned char i;\n\n"
                "    charset_install();\n"
                "    for (i = 0; i < %d; ++i) {\n"
                "        charset_define(codes[i], glyphs[i]);\n"
                "    }\n}\n" % len(tiles))

    # Names live in their own module so only the preview tool links them in.
    with open("src/lib/tiles_names.c", "w") as c:
        c.write("/* GENERATED by tools/mktiles.py from %s -- do not edit. */\n\n"
                "#include <q4k/tiles.h>\n\n"
                "const char *const tile_names[TILE_TOTAL] = {\n" % src)
        for t in tiles:
            c.write('    "%s",\n' % t.name.upper())
        c.write("};\n\nconst unsigned char tile_codes[TILE_TOTAL] = {\n")
        for t in tiles:
            c.write("    0x%02X,\n" % t.code)
        c.write("};\n")

    print("mktiles: %d tiles ($%02X-$%02X), %d terrain, %d actors"
          % (len(tiles), tiles[0].code, tiles[-1].code, len(terrain),
             len(tiles) - len(terrain)))


if __name__ == "__main__":
    main()
